use crate::kv::{flatten_kv_strings, parse_key_values};
use crate::metadata::compute_content_fingerprint;
use crate::reader::{parse_vpk, read_vpk_entry};
use crate::writer::{write_vpk, VpkFileToWrite};
use chrono::Utc;
use l4a_protocol::WorkshopId;
use serde::{Deserialize, Serialize};
use std::collections::BTreeMap;
use std::path::Path;
use std::str::FromStr;

const LEGACY_DUMMY_DESCRIPTION: &str = "A dummy addon generated by Left 4 Addons";

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct DummyMetadata {
    pub schema_version: u8,
    pub workshop_id: Option<WorkshopId>,
    pub original_hash: Option<String>,
    pub original_size: Option<u64>,
    pub original_time_updated: Option<i64>,
    pub generated_at: Option<String>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum DummyInspection {
    Dummy(DummyMetadata),
    RealVpk {
        content_hash: String,
        file_size: u64,
        title: Option<String>,
    },
    Corrupted(String),
}

#[derive(Debug, Clone)]
pub struct DummySpec {
    pub workshop_id: WorkshopId,
    pub original_hash: String,
    pub original_size: u64,
    pub original_time_updated: Option<i64>,
}

/// 生成 v2 Dummy VPK（嵌入原包的指纹、大小与更新时间戳，供对账引擎精确检测游戏覆写）。
pub fn generate_dummy_vpk<P: AsRef<Path>, Q: AsRef<Path>>(
    original_vpk_path: P,
    dummy_vpk_path: Q,
    spec: &DummySpec,
) -> Result<DummyMetadata, String> {
    let mut archive = parse_vpk(&original_vpk_path).map_err(|e| e.to_string())?;

    let mut steam_app_id = "550".to_string();
    let mut addon_version = "1.0".to_string();
    let raw_file_name = original_vpk_path
        .as_ref()
        .file_name()
        .and_then(|n| n.to_str())
        .unwrap_or("Workshop Addon");
    let mut addon_title = strip_vpk_suffixes(raw_file_name).to_string();

    if let Some(key) = archive
        .entries
        .keys()
        .find(|k| {
            let lower = k.to_ascii_lowercase();
            lower == "addoninfo.txt"
                || lower.ends_with("/addoninfo.txt")
                || lower.ends_with("\\addoninfo.txt")
        })
        .cloned()
    {
        if let Some(entry) = archive.entries.get(&key) {
            if let Ok(bytes) = read_vpk_entry(&mut archive.file, entry) {
                let text = String::from_utf8_lossy(&bytes);
                let map = flatten_kv_strings(&parse_key_values(&text));
                if let Some(v) = map.get("addonsteamappid").filter(|s| !s.trim().is_empty()) {
                    steam_app_id = v.clone();
                }
                if let Some(v) = map.get("addonversion").filter(|s| !s.trim().is_empty()) {
                    addon_version = v.clone();
                }
                if let Some(v) = map.get("addontitle").filter(|s| !s.trim().is_empty()) {
                    addon_title = v.clone();
                }
            }
        }
    }

    let mut files_to_write = Vec::new();
    for (ext, target) in [("jpg", "addonimage.jpg"), ("vtf", "addonimage.vtf")] {
        let found = archive
            .entries
            .keys()
            .find(|k| {
                let lower = k.to_ascii_lowercase();
                lower == target
                    || lower.ends_with(&format!("/{target}"))
                    || lower.ends_with(&format!("\\{target}"))
            })
            .cloned();
        if let Some(key) = found {
            if let Some(entry) = archive.entries.get(&key) {
                if let Ok(bytes) = read_vpk_entry(&mut archive.file, entry) {
                    files_to_write.push(VpkFileToWrite {
                        ext: ext.to_string(),
                        path: String::new(),
                        filename: "addonimage".to_string(),
                        content: bytes,
                    });
                }
            }
        }
    }

    let generated_at = Utc::now().to_rfc3339();
    let escaped_app_id = escape_kv_value(&steam_app_id);
    let escaped_version = escape_kv_value(&addon_version);
    let escaped_title = escape_kv_value(&addon_title);
    let time_updated_line = spec
        .original_time_updated
        .map(|ts| format!("    \"l4aOriginalTimeUpdated\" \"{ts}\"\n"))
        .unwrap_or_default();

    let addoninfo_content = format!(
        "\"AddonInfo\"\n{{\n    \"addonSteamAppID\" \"{}\"\n    \"addonversion\" \"{}\"\n    \"addontitle\" \"{} (L4A Dummy)\"\n    \"addonDescription\" \"{}\"\n    \"l4aDummy\" \"2\"\n    \"l4aWorkshopId\" \"{}\"\n    \"l4aOriginalHash\" \"{}\"\n    \"l4aOriginalSize\" \"{}\"\n{}    \"l4aGeneratedAt\" \"{}\"\n}}\n",
        escaped_app_id,
        escaped_version,
        escaped_title,
        LEGACY_DUMMY_DESCRIPTION,
        spec.workshop_id,
        spec.original_hash,
        spec.original_size,
        time_updated_line,
        generated_at
    );

    files_to_write.push(VpkFileToWrite {
        ext: "txt".to_string(),
        path: String::new(),
        filename: "addoninfo".to_string(),
        content: addoninfo_content.into_bytes(),
    });

    write_vpk(dummy_vpk_path, &files_to_write)?;

    Ok(DummyMetadata {
        schema_version: 2,
        workshop_id: Some(spec.workshop_id),
        original_hash: Some(spec.original_hash.clone()),
        original_size: Some(spec.original_size),
        original_time_updated: spec.original_time_updated,
        generated_at: Some(generated_at),
    })
}

/// 检测指定 `.vpk` 是 v1/v2 Dummy 还是真实模组包。
pub fn inspect_dummy_vpk<P: AsRef<Path>>(path: P) -> DummyInspection {
    let file_size = match std::fs::metadata(&path) {
        Ok(m) => m.len(),
        Err(e) => return DummyInspection::Corrupted(e.to_string()),
    };

    let mut archive = match parse_vpk(&path) {
        Ok(a) => a,
        Err(e) => return DummyInspection::Corrupted(e.to_string()),
    };

    let mut addoninfo_text = String::new();
    let mut info_map = BTreeMap::new();
    if let Some(key) = archive
        .entries
        .keys()
        .find(|k| {
            let lower = k.to_ascii_lowercase();
            lower == "addoninfo.txt"
                || lower.ends_with("/addoninfo.txt")
                || lower.ends_with("\\addoninfo.txt")
        })
        .cloned()
    {
        if let Some(entry) = archive.entries.get(&key) {
            if let Ok(bytes) = read_vpk_entry(&mut archive.file, entry) {
                addoninfo_text = String::from_utf8_lossy(&bytes).into_owned();
                info_map = flatten_kv_strings(&parse_key_values(&addoninfo_text));
            }
        }
    }

    let marker = info_map.get("l4adummy").map(|v| v.trim());
    let is_legacy_desc = info_map
        .get("addondescription")
        .is_some_and(|d| d.trim() == LEGACY_DUMMY_DESCRIPTION);

    match marker {
        Some("2") => {
            let workshop_id = info_map
                .get("l4aworkshopid")
                .and_then(|s| WorkshopId::from_str(s).ok());
            let original_hash = info_map
                .get("l4aoriginalhash")
                .filter(|s| !s.trim().is_empty())
                .cloned();
            let original_size = info_map
                .get("l4aoriginalsize")
                .and_then(|s| s.trim().parse::<u64>().ok());
            let original_time_updated = info_map
                .get("l4aoriginaltimeupdated")
                .and_then(|s| s.trim().parse::<i64>().ok());
            let generated_at = info_map.get("l4ageneratedat").cloned();

            DummyInspection::Dummy(DummyMetadata {
                schema_version: 2,
                workshop_id,
                original_hash,
                original_size,
                original_time_updated,
                generated_at,
            })
        }
        Some("1") => DummyInspection::Dummy(DummyMetadata {
            schema_version: 1,
            workshop_id: info_map
                .get("l4aworkshopid")
                .and_then(|s| WorkshopId::from_str(s).ok()),
            original_hash: None,
            original_size: None,
            original_time_updated: None,
            generated_at: None,
        }),
        None if is_legacy_desc => DummyInspection::Dummy(DummyMetadata {
            schema_version: 1,
            workshop_id: None,
            original_hash: None,
            original_size: None,
            original_time_updated: None,
            generated_at: None,
        }),
        _ => {
            let content_hash = compute_content_fingerprint(&archive.entries, &addoninfo_text);
            let title = info_map
                .get("addontitle")
                .map(|s| s.trim().to_string())
                .filter(|s| !s.is_empty());
            DummyInspection::RealVpk {
                content_hash,
                file_size,
                title,
            }
        }
    }
}

fn strip_vpk_suffixes(name: &str) -> &str {
    let lower = name.to_ascii_lowercase();
    if lower.ends_with(".vpk.disabled") {
        &name[..name.len() - ".vpk.disabled".len()]
    } else if lower.ends_with(".disabled") {
        &name[..name.len() - ".disabled".len()]
    } else if lower.ends_with(".vpk") {
        &name[..name.len() - ".vpk".len()]
    } else {
        name
    }
}

fn escape_kv_value(raw: &str) -> String {
    let mut out = String::with_capacity(raw.len());
    for c in raw.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\r' | '\n' => out.push(' '),
            other => out.push(other),
        }
    }
    out
}
